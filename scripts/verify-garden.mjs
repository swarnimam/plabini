import assert from 'node:assert/strict';
import { nearestChapter, scrollFraction } from '../src/lib/garden-state.ts';
assert.equal(nearestChapter([], 400), -1);
assert.equal(nearestChapter([400, 1200, 2000, 2800], 400), 0);
assert.equal(nearestChapter([-1200, -400, 400, 1200], 400), 2);
assert.equal(nearestChapter([-2200, -1400, -600, 200], 400), 3);
assert.equal(nearestChapter([0, 800], 400), 0, 'Stable tie at a chapter boundary');
assert.equal(scrollFraction(500, 2000, 1000), .5);
assert.equal(scrollFraction(-40, 2000, 1000), 0, 'Clamp elastic scrolling');
assert.equal(scrollFraction(5000, 2000, 1000), 1);
assert.equal(scrollFraction(0, 800, 1000), 0, 'Short pages do not divide by zero');
console.log('Verified ceremony selection boundaries and reading progress.');
